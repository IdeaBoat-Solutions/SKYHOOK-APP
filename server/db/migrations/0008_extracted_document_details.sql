-- 0008_extracted_document_details.sql
--
-- Extracted document data from the four scanned PDFs in public/ocr:
--   1. Fact Sheet Sanction Letter (2).pdf            -> loan_sanction
--   2. FITNESS CERTIFICATE GJ38S-2733 NEW CRANE.pdf  -> fitness_certificate
--   3. Tata AIG Motor Premium Quote_3184_...pdf      -> insurance_quote
--   4. VAHANP_3.PDF                                  -> tax_receipt
--
-- Run this whole file once in the Supabase SQL Editor. Forward-only and safe
-- to re-run: tables/indexes/policies are guarded and the seed uses an upsert.
--
-- Data is inserted for every tenant that exists at the time of the run (the
-- tenant UUID is generated by the seed script, so it is not hard-coded here).
-- Follow the pattern of 0006_machine_rc_details.sql: the ~25 descriptive
-- fields of each document live in one JSONB column, shown and reviewed
-- together but not queried individually. A few summary columns are kept
-- alongside it for filtering and list rendering.

BEGIN;

SET search_path = skyhook, public;

/* -------------------------------------------------------------------------- */
/* 1. Table                                                                    */
/* -------------------------------------------------------------------------- */

CREATE TABLE IF NOT EXISTS extracted_documents (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id UUID NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  doc_type TEXT NOT NULL CHECK (doc_type IN (
    'loan_sanction', 'fitness_certificate', 'insurance_quote', 'tax_receipt'
  )),
  title TEXT NOT NULL,
  source_file TEXT NOT NULL,
  /** Stable identifier inside the document: application / certificate / quote / receipt no. */
  natural_key TEXT NOT NULL,
  entity_name TEXT NOT NULL DEFAULT '',
  vehicle_number TEXT,
  issue_date DATE,
  expiry_date DATE,
  /** Headline amount for this document in paise (rupees x 100); NULL when not applicable. */
  amount_paise BIGINT,
  amount_label TEXT,
  details JSONB NOT NULL DEFAULT '{}'::jsonb,
  scanned_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, doc_type, natural_key)
);

CREATE INDEX IF NOT EXISTS ix_extracted_documents_tenant_type
  ON extracted_documents (tenant_id, doc_type);
CREATE INDEX IF NOT EXISTS ix_extracted_documents_vehicle
  ON extracted_documents (tenant_id, vehicle_number);

-- The base trigger loop in 0001 ran before this table existed, so add its
-- updated_at trigger explicitly.
DROP TRIGGER IF EXISTS trg_extracted_documents_updated ON extracted_documents;
CREATE TRIGGER trg_extracted_documents_updated
  BEFORE UPDATE ON extracted_documents
  FOR EACH ROW EXECUTE FUNCTION skyhook.set_updated_at();

COMMENT ON TABLE extracted_documents IS
  'Structured data extracted from scanned PDF documents (loan sanction, fitness, insurance quote, tax receipt).';
COMMENT ON COLUMN extracted_documents.details IS
  'Full extracted document payload; nested objects and arrays (e.g. amortization schedule) are preserved.';

/* -------------------------------------------------------------------------- */
/* 2. Row-level security (tenant isolation)                                    */
/* -------------------------------------------------------------------------- */

ALTER TABLE extracted_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE extracted_documents FORCE ROW LEVEL SECURITY;

-- PostgreSQL has no CREATE POLICY IF NOT EXISTS, so guard via the catalog.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = current_schema()
      AND tablename = 'extracted_documents'
      AND policyname = 'tenant_isolation'
  ) THEN
    CREATE POLICY tenant_isolation ON extracted_documents
      USING (tenant_id = current_setting('app.tenant_id', true)::uuid)
      WITH CHECK (tenant_id = current_setting('app.tenant_id', true)::uuid);
  END IF;
END $$;

GRANT USAGE ON SCHEMA skyhook TO skyhook_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON extracted_documents TO skyhook_app;

